"""Build the two synthetic sample files that ship with this toolkit.

The toolkit ships a small extract so that every notebook in the book runs
end to end without access to any national data. This script documents exactly
how that extract was produced, and regenerates it from the full synthetic
source files.

Source
------
Two synthetic administrative registers, generated by Nicolas Libuy (2024) from
frequency tables supplied by the Instituto Nacional de Estadisticas (INE) of
Chile. They reproduce the observed frequency and error structure of the
identifying variables in Chile's health-insurance (Fonasa) and social-security
(Suseso) registers. They contain no real records and no real people.

The full files are ~1.6 GB in total and are not distributed with this
repository. Point --source-dir at the directory that holds:

    synthetic_linked_fonasa_left.csv
    synthetic_linked_suseso_right.csv

Sampling design
---------------
A stratified sample with a known number of true cross-register matches:

  * 4,500 person identifiers that appear in BOTH registers -> 4,500 true matches
  * fillers drawn only from identifiers that appear in NEITHER intersection,
    so the number of true matches in the extract is exactly 4,500

giving 30,000 Fonasa records and 27,000 Suseso records. The seed is fixed, so
re-running this script reproduces the shipped files byte for byte.

The extract keeps the registers in their RAW state: names and categories are
uncleaned and unstandardised, exactly as they arrive from a source system.
Cleaning, standardisation and pseudonymisation are steps the toolkit performs.

Record identifiers are renumbered (F0000001..., S0000001...) so that they carry
no information. In the source files the Fonasa row number happens to coincide
with the person identifier, which would let a reader recover matches from the
row number rather than from the identifying variables.

Usage
-----
    python scripts/build_sample_dataset.py --source-dir /path/to/full/csvs
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

SEED = 42
N_TRUE_MATCHES = 4_500
N_FONASA = 30_000
N_SUSESO = 27_000

# Columns kept in the published extract. `fuente` and `tipo` are dropped: they
# are artefacts of how the synthetic data was generated and carry no meaning
# for linkage. `rut_veradero` is renamed to `true_person_id` because it exists
# only as a ground-truth key for evaluation, not as a register field.
SOURCE_COLS = ["unique_id", "nombre", "ap1", "ap2", "sexo", "nacionalidad", "rut_veradero"]
OUTPUT_COLS = ["unique_id", "nombre", "ap1", "ap2", "sexo", "nacionalidad", "true_person_id"]


def load_register(path: Path) -> pd.DataFrame:
    """Read one full synthetic register, keeping only the columns we publish."""
    df = pd.read_csv(
        path,
        usecols=SOURCE_COLS,
        dtype={"unique_id": "string", "rut_veradero": "string"},
    )
    return df.rename(columns={"rut_veradero": "true_person_id"})


def build_sample(
    fonasa: pd.DataFrame, suseso: pd.DataFrame
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Draw the stratified sample described in the module docstring."""
    fonasa_ids = set(fonasa["true_person_id"].dropna())
    suseso_ids = set(suseso["true_person_id"].dropna())
    shared = sorted(fonasa_ids & suseso_ids)
    print(f"  person ids present in both registers: {len(shared):,}")

    if len(shared) < N_TRUE_MATCHES:
        raise SystemExit(
            f"only {len(shared):,} shared ids available, need {N_TRUE_MATCHES:,}"
        )

    sampled_shared = set(
        pd.Series(shared).sample(n=N_TRUE_MATCHES, random_state=SEED)
    )

    out = []
    for name, prefix, df, n_target in (
        ("fonasa", "F", fonasa, N_FONASA),
        ("suseso", "S", suseso, N_SUSESO),
    ):
        # One record per sampled shared identifier: exactly N_TRUE_MATCHES
        # true pairs, with no ambiguity about which record pairs with which.
        matched = (
            df[df["true_person_id"].isin(sampled_shared)]
            .drop_duplicates(subset="true_person_id", keep="first")
        )

        # Fillers cannot belong to ANY shared identifier, otherwise they would
        # create true matches beyond the 4,500 the design specifies.
        fillers = df[~df["true_person_id"].isin(fonasa_ids & suseso_ids)]
        fillers = fillers.sample(n=n_target - len(matched), random_state=SEED)

        sample = (
            pd.concat([matched, fillers])
            .sample(frac=1, random_state=SEED)  # shuffle so matches aren't first
            .reset_index(drop=True)
        )
        # Opaque record identifiers, assigned after shuffling.
        sample["unique_id"] = [f"{prefix}{i:07d}" for i in range(1, len(sample) + 1)]
        print(f"  {name}: {len(sample):,} records ({len(matched):,} with a true match)")
        out.append(sample[OUTPUT_COLS])

    return out[0], out[1]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source-dir",
        type=Path,
        required=True,
        help="directory holding the full synthetic_linked_*.csv files",
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=Path(__file__).resolve().parent.parent / "data",
        help="where to write the extract (default: the repository's data/ folder)",
    )
    args = parser.parse_args()

    print("Reading full synthetic registers (this takes a minute)...")
    fonasa = load_register(args.source_dir / "synthetic_linked_fonasa_left.csv")
    suseso = load_register(args.source_dir / "synthetic_linked_suseso_right.csv")
    print(f"  fonasa: {len(fonasa):,} records | suseso: {len(suseso):,} records")

    print("Building stratified sample...")
    fonasa_sample, suseso_sample = build_sample(fonasa, suseso)

    args.out_dir.mkdir(parents=True, exist_ok=True)
    for name, sample in (("fonasa", fonasa_sample), ("suseso", suseso_sample)):
        path = args.out_dir / f"{name}_sample.csv"
        sample.to_csv(path, index=False)
        print(f"  wrote {path} ({path.stat().st_size / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
